#!/usr/bin/env node
/**
 * After `astro build`, derive deployment files from the built site:
 *   dist/_headers, dist/_redirects      Cloudflare (Workers static assets / Pages) format
 *   deploy/generated/*.conf, *.caddy    snippets for Nginx and Caddy
 *
 * The Content-Security-Policy lists the SHA-256 hash of every inline script the
 * build produced, so no 'unsafe-inline' is needed for scripts. Hashes change when
 * Starlight or the content changes, which is why this runs on every build.
 *
 * CSP_MODE=enforce  -> Content-Security-Policy
 * CSP_MODE=report   -> Content-Security-Policy-Report-Only (default until verified in a browser)
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const dist = path.join(root, 'dist');
if (!fs.existsSync(dist)) { console.error('dist/ not found'); process.exit(1); }
const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);

// 1. inline script hashes
const hashes = new Set();
for (const f of walk(dist).filter((f) => f.endsWith('.html'))) {
  const html = fs.readFileSync(f, 'utf8');
  for (const m of html.matchAll(/<script(?![^>]*\bsrc=)([^>]*)>([\s\S]*?)<\/script>/g)) {
    if (/application\/(ld\+)?json/.test(m[1]) || !m[2].trim()) continue;
    hashes.add(`'sha256-${crypto.createHash('sha256').update(m[2]).digest('base64')}'`);
  }
}

// 2. headers
const mode = (process.env.CSP_MODE ?? 'report').toLowerCase();
const csp = [
  "default-src 'self'",
  `script-src 'self' 'wasm-unsafe-eval' ${[...hashes].sort().join(' ')}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self' blob:",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
  'upgrade-insecure-requests',
].join('; ');
const security = {
  [mode === 'enforce' ? 'Content-Security-Policy' : 'Content-Security-Policy-Report-Only']: csp,
  'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
  'X-Content-Type-Options': 'nosniff',
  'X-Frame-Options': 'DENY',
  'Referrer-Policy': 'strict-origin-when-cross-origin',
  'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=(), interest-cohort=()',
  'Cross-Origin-Opener-Policy': 'same-origin',
  'Cross-Origin-Resource-Policy': 'same-site',
};
const cache = [
  ['/_astro/*', 'public, max-age=31536000, immutable'],
  ['/pagefind/*', 'public, max-age=3600'],
  ['/*.svg', 'public, max-age=86400'],
];
const htmlCache = 'public, max-age=0, must-revalidate';

// Cloudflare format
let cf = '/*\n' + Object.entries(security).map(([k, v]) => `  ${k}: ${v}`).join('\n') + `\n  Cache-Control: ${htmlCache}\n`;
for (const [p, v] of cache) cf += `\n${p}\n  Cache-Control: ${v}\n`;
fs.writeFileSync(path.join(dist, '_headers'), cf);

// 3. redirects (301). Astro emits meta-refresh stubs; real 301s are better for SEO.
const redirects = JSON.parse(fs.readFileSync(path.join(root, 'data/redirects.json'), 'utf8'));
const repos = JSON.parse(fs.readFileSync(path.join(root, 'data/github-repos.json'), 'utf8')).repositories.filter((r) => !r.isPrivate);
const all = [...redirects, { from: '/projects/', to: '/repos/' },
  ...repos.map((r) => { const s = r.name.toLowerCase().replace(/[^\w-]+/g, ''); return { from: `/projects/${s}/`, to: `/repos/${s}/` }; })];
fs.writeFileSync(path.join(dist, '_redirects'), all.map((r) => `${r.from} ${r.to} 301`).join('\n') + '\n');

// 4. Nginx / Caddy snippets (kept out of dist so they are never served)
const gen = path.join(root, 'deploy/generated');
fs.mkdirSync(gen, { recursive: true });
const esc = (v) => v.replace(/"/g, '\\"');
fs.writeFileSync(path.join(gen, 'security-headers.nginx.conf'),
  '# GENERATED by scripts/postbuild-headers.mjs. Include inside the server block.\n' +
  Object.entries(security).map(([k, v]) => `add_header ${k} "${esc(v)}" always;`).join('\n') + '\n');
fs.writeFileSync(path.join(gen, 'redirects.nginx.conf'),
  '# GENERATED. Include inside the server block.\n' + all.map((r) => `location = ${r.from} { return 301 ${r.to}; }`).join('\n') + '\n');
fs.writeFileSync(path.join(gen, 'security-headers.caddy'),
  '# GENERATED by scripts/postbuild-headers.mjs. Import inside a site block.\n(security_headers) {\n  header {\n' +
  Object.entries(security).map(([k, v]) => `    ${k} "${esc(v)}"`).join('\n') + '\n    -Server\n  }\n}\n');
fs.writeFileSync(path.join(gen, 'redirects.caddy'),
  '# GENERATED. Import inside a site block.\n(legacy_redirects) {\n' + all.map((r) => `  redir ${r.from} ${r.to} permanent`).join('\n') + '\n}\n');

console.log(`postbuild: ${hashes.size} inline-script hashes, ${all.length} redirects, CSP mode "${mode}" -> dist/_headers, dist/_redirects, deploy/generated/`);
